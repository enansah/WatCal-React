// Shared CSV and PDF downloads for the landlord pages (Analysis, History).

const WATERMARK = "/Landlord/images/backLogo.png";

export const safeName = (s) => String(s).replace(/[^a-z0-9_-]/gi, "_");
const csvCell = (v) => `"${String(v ?? "").replace(/"/g, '""')}"`;

function saveBlob(filename, blob) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/**
 * CSV with a Label,Value summary and, optionally, a table underneath.
 * summary: [[label, value], ...]   table: { head: [...], rows: [[...], ...] }
 */
export function downloadCsv({ filename, summary, table }) {
  const lines = [["Label", "Value"], ...summary].map((row) => row.map(csvCell).join(","));
  if (table && table.rows.length) {
    lines.push("", table.head.map(csvCell).join(","), ...table.rows.map((row) => row.map(csvCell).join(",")));
  }
  saveBlob(filename, new Blob([lines.join("\r\n")], { type: "text/csv;charset=utf-8" }));
}

// Load an image from the site as a data URL for jsPDF; null if it can't be loaded
async function loadImage(src) {
  try {
    const blob = await (await fetch(src)).blob();
    return await new Promise((resolve, reject) => {
      const reader = new FileReader();
      reader.onload = () => resolve(reader.result);
      reader.onerror = reject;
      reader.readAsDataURL(blob);
    });
  } catch {
    return null;
  }
}

/**
 * "Summary Report" PDF: title, subtitle, a context line, Label: Value rows, and an optional table.
 * Values must use plain text (e.g. "GHS 12.00"): the built-in PDF font has no cedi sign.
 */
export async function downloadPdf({ filename, title = "Summary Report", subtitle = "WatCal User Consumption", context, summary, table }) {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const watermark = await loadImage(WATERMARK);

  // Faded logo in the middle of every page, behind the text
  const decoratePage = () => {
    if (!watermark) return;
    const size = 150;
    doc.saveGraphicsState();
    doc.setGState(new doc.GState({ opacity: 0.12 }));
    doc.addImage(watermark, "PNG", (pageWidth - size) / 2, (pageHeight - size) / 2, size, size);
    doc.restoreGraphicsState();
  };
  decoratePage();

  // Brand bar
  doc.setFillColor(26, 26, 26);
  doc.rect(0, 0, pageWidth, 18, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(255, 255, 255);
  doc.text("Wat", 10, 12);
  doc.setTextColor(6, 204, 2);
  doc.text("Cal", 10 + doc.getTextWidth("Wat"), 12);

  doc.setTextColor(26, 26, 26);
  doc.setFontSize(22);
  doc.text(title, 10, 35);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(16);
  doc.text(subtitle, 10, 45);

  let y = 52;
  if (context) {
    doc.setFontSize(10);
    doc.setTextColor(100, 100, 100);
    doc.text(context, 10, y);
    doc.setTextColor(26, 26, 26);
    y += 6;
  }

  // Label: Value rows
  y += 6;
  doc.setFontSize(12);
  for (const [label, value] of summary) {
    doc.setFont("helvetica", "bold");
    doc.text(`${label}:`, 10, y);
    doc.setFont("helvetica", "normal");
    doc.text(String(value ?? "N/A"), 75, y);
    y += 10;
  }

  // Optional table, continued on new pages as needed
  if (table) {
    y += 4;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(14);
    doc.text(table.title || "Readings", 10, y);
    y += 8;

    const columns = table.head.length;
    const colWidth = (pageWidth - 20) / columns;
    const drawHead = () => {
      doc.setFillColor(6, 204, 2);
      doc.rect(10, y - 5, pageWidth - 20, 8, "F");
      doc.setFont("helvetica", "bold");
      doc.setFontSize(11);
      doc.setTextColor(26, 26, 26);
      table.head.forEach((h, i) => doc.text(String(h), 12 + i * colWidth, y));
      y += 8;
      doc.setFont("helvetica", "normal");
    };
    drawHead();

    if (table.rows.length === 0) {
      doc.text(table.empty || "No readings yet", 12, y);
    }
    table.rows.forEach((row, r) => {
      if (y > pageHeight - 15) {
        doc.addPage();
        decoratePage();
        y = 20;
        drawHead();
      }
      if (r % 2 === 0) {
        doc.setFillColor(245, 245, 245);
        doc.rect(10, y - 5, pageWidth - 20, 7, "F");
      }
      row.forEach((cell, i) => doc.text(String(cell), 12 + i * colWidth, y));
      y += 7;
    });
  }

  // Footer with page numbers
  const pages = doc.getNumberOfPages();
  for (let p = 1; p <= pages; p++) {
    doc.setPage(p);
    doc.setFontSize(9);
    doc.setTextColor(140, 140, 140);
    doc.text(`Generated by WatCal on ${new Date().toLocaleString()}`, 10, pageHeight - 8);
    doc.text(`Page ${p} of ${pages}`, pageWidth - 10, pageHeight - 8, { align: "right" });
  }

  doc.save(filename);
}
